export function SocialIcon({
  platform,
  icon,
  className = "h-4 w-4",
}: {
  platform: string;
  icon: Media | null;
  className?: string;
}) {
  if (icon) {
    return (
      <Image
        src={mediaUrlFor(icon)}
        alt={icon.alt_he}
        width={20}
        height={20}
        className="h-5 w-5 object-contain"
      />
    );
  }

  const path = BUILT_IN[platform.trim().toLowerCase()];
  if (path) {
    return (
      <svg viewBox="0 0 24 24" fill="currentColor" aria-hidden="true" className={className}>
        <path d={path} />
      </svg>
    );
  }

  // Unrecognised platform name — better a letter than an empty circle.
  return <span aria-hidden="true">{platform.slice(0, 1).toUpperCase()}</span>;
}

